import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import net from 'node:net';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test, { after, before } from 'node:test';
import postgres from 'postgres';

import { runOpsStaffProvision } from '../src/admin/admin-provisioning.ts';

const clusterRoot = mkdtempSync(join(tmpdir(), 'icao-op-'));
const dataDirectory = join(clusterRoot, 'data');
const socketDirectory = join(clusterRoot, 'socket');
const repositoryRoot = join(clusterRoot, 'repo');
const protectedDirectory = join(clusterRoot, 'protected');
const inputFile = join(protectedDirectory, 'input.json');
const outputFile = join(protectedDirectory, 'credentials.json');
const duplicateOutputFile = join(protectedDirectory, 'duplicate-credentials.json');
let databaseUrl;
let port;

function requireBinary(name) {
  const result = spawnSync('sh', ['-c', `command -v ${name}`], { encoding: 'utf8' });
  assert.equal(result.status, 0, `missing_required_postgres_binary:${name}`);
  return result.stdout.trim();
}

function availablePort() {
  return new Promise((resolve, reject) => {
    const server = net.createServer();
    server.once('error', reject);
    server.listen(0, '127.0.0.1', () => {
      const address = server.address();
      assert.ok(address && typeof address === 'object');
      const selectedPort = address.port;
      server.close((error) => (error ? reject(error) : resolve(selectedPort)));
    });
  });
}

function psql(input) {
  return spawnSync(requireBinary('psql'), [
    '-X',
    '-q',
    '-v',
    'ON_ERROR_STOP=1',
    '-h',
    socketDirectory,
    '-p',
    String(port),
    '-U',
    'postgres',
    '-d',
    'postgres',
  ], {
    input,
    encoding: 'utf8',
    env: { ...process.env, LC_ALL: 'C' },
  });
}

before(async () => {
  port = await availablePort();
  mkdirSync(socketDirectory);
  mkdirSync(repositoryRoot, { mode: 0o700 });
  mkdirSync(protectedDirectory, { mode: 0o700 });
  writeFileSync(inputFile, JSON.stringify({
    email: 'support@yunqihangke.com',
    password: 'test-only-random-password-32-chars',
    role: 'admin',
  }), { mode: 0o600 });
  execFileSync(requireBinary('initdb'), [
    '-D',
    dataDirectory,
    '-A',
    'trust',
    '-U',
    'postgres',
    '--no-locale',
  ], { stdio: 'ignore' });
  execFileSync(requireBinary('pg_ctl'), [
    '-D',
    dataDirectory,
    '-o',
    `-F -k ${socketDirectory} -p ${port}`,
    '-w',
    'start',
  ], { stdio: 'ignore' });
  const bootstrap = psql(`
    CREATE TABLE ops_staff_accounts (
      id uuid PRIMARY KEY,
      email text NOT NULL UNIQUE,
      role text NOT NULL CHECK (role IN ('admin', 'support')),
      password_hash text NOT NULL,
      totp_secret_ciphertext text NOT NULL,
      totp_secret_iv text NOT NULL,
      totp_secret_tag text NOT NULL,
      totp_confirmed_at timestamptz NOT NULL,
      password_changed_at timestamptz NOT NULL DEFAULT now(),
      last_totp_step bigint NOT NULL DEFAULT 0,
      disabled_at timestamptz,
      created_at timestamptz NOT NULL DEFAULT now(),
      updated_at timestamptz NOT NULL DEFAULT now()
    );
    CREATE TABLE ops_staff_recovery_codes (
      id uuid PRIMARY KEY,
      staff_id uuid NOT NULL REFERENCES ops_staff_accounts(id) ON DELETE RESTRICT,
      code_hash text NOT NULL,
      consumed_at timestamptz,
      created_at timestamptz NOT NULL DEFAULT now()
    );
    CREATE TABLE ops_audit_events (
      sequence bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      request_id text NOT NULL,
      actor_staff_id uuid REFERENCES ops_staff_accounts(id) ON DELETE RESTRICT,
      actor_role text,
      action text NOT NULL,
      target_type text NOT NULL,
      target_id text,
      reason text NOT NULL,
      before_state jsonb,
      after_state jsonb,
      metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
      created_at timestamptz NOT NULL DEFAULT now()
    );
  `);
  assert.equal(bootstrap.status, 0, bootstrap.stderr);
  databaseUrl = `postgresql://postgres@127.0.0.1:${port}/postgres`;
});

after(async () => {
  if (existsSync(dataDirectory)) {
    spawnSync(requireBinary('pg_ctl'), [
      '-D',
      dataDirectory,
      '-m',
      'fast',
      '-w',
      'stop',
    ], { stdio: 'ignore' });
  }
  rmSync(clusterRoot, { recursive: true, force: true });
});

test('staff provisioning inserts recovery rows with real postgres-js transaction semantics', async () => {
  const environment = {
    DATABASE_URL: databaseUrl,
    OPS_PROVISION_INPUT_FILE: inputFile,
    OPS_PROVISION_OUTPUT_FILE: outputFile,
    OPS_SESSION_HASH_SECRET: 'test-only-session-hash-secret-at-least-32-bytes',
    OPS_TOTP_ENCRYPTION_KEY: Buffer.alloc(32, 7).toString('base64'),
  };

  await runOpsStaffProvision(environment, repositoryRoot);

  assert.equal(statSync(outputFile).mode & 0o777, 0o600);
  const delivery = JSON.parse(readFileSync(outputFile, 'utf8'));
  assert.equal(delivery.email, 'support@yunqihangke.com');
  assert.equal(delivery.role, 'admin');
  assert.equal(delivery.recoveryCodes.length, 10);
  assert.equal(new Set(delivery.recoveryCodes).size, 10);

  const database = postgres(databaseUrl, { max: 1, prepare: false });
  try {
    const [counts] = await database`
      select
        (select count(*)::integer from ops_staff_accounts) as staff_count,
        (
          select count(*)::integer
          from ops_staff_accounts
          where email = 'support@yunqihangke.com'
            and role = 'admin'
            and disabled_at is null
        ) as active_admin_count,
        (select count(*)::integer from ops_staff_recovery_codes) as recovery_code_count,
        (
          select count(*)::integer
          from ops_audit_events
          where action = 'ops.staff.provision'
        ) as audit_event_count
    `;
    assert.deepEqual(counts, {
      active_admin_count: 1,
      audit_event_count: 1,
      recovery_code_count: 10,
      staff_count: 1,
    });
  } finally {
    await database.end({ timeout: 5 });
  }

  await assert.rejects(
    runOpsStaffProvision({
      ...environment,
      OPS_PROVISION_OUTPUT_FILE: duplicateOutputFile,
    }, repositoryRoot),
    /ops_staff_email_exists/u,
  );
  assert.equal(existsSync(duplicateOutputFile), false);
});
