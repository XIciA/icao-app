import { act, renderHook, waitFor } from '@testing-library/react-native';
import { useQuestionBank } from '../hooks/useQuestionBank.native';
import { useQuestionBankTopic } from '../hooks/useQuestionBankTopic.native';
import { loadQuestionBank, questionBankRepository } from '../data/repository.native';
import { beginCommerceEntitlementGeneration, publishCommerceEntitlementChange, resetCommerceEntitlementEventsForTests } from '@/features/native-commercial-testflight/commerce-entitlement-events';
import type { QuestionBankDataset, QuestionBankTopic } from '../types';
jest.mock('../data/repository.native',()=>({subscribeQuestionBankCatalog:()=>()=>undefined,loadQuestionBank:jest.fn(),questionBankRepository:{getTopic:jest.fn()}}));
jest.mock('@/features/account/profile-store.native',()=>({useProfile:()=>({studyScope:'all',target:'icao5'})}));
jest.mock('@/features/native-commercial-testflight/commerce-environment',()=>({nativeCommerceEnvironmentSnapshot:()=> 'production',subscribeNativeCommerceEnvironment:()=>()=>undefined}));
jest.mock('../lib/study-scope',()=>({scopeDataset:(value:unknown)=>value,scopeTopic:(_bank:unknown,value:unknown)=>value}));
const topic={id:'topic',name:'Topic',declaredCardCount:2,cards:[],scopeCardIds:{all:[],core:[],crash:[]}} as unknown as QuestionBankTopic;
const dataset={id:'opi',categories:[],access:{membershipActive:false}} as unknown as QuestionBankDataset;
beforeEach(()=>{resetCommerceEntitlementEventsForTests();jest.clearAllMocks();jest.mocked(loadQuestionBank).mockResolvedValue({dataset,source:'remote'});jest.mocked(questionBankRepository.getTopic).mockResolvedValue(topic);});
it.each(['opi','radiotelephony'] as const)('reloads %s directory and topic on same-account membership activation, not unrelated refreshes',async(bank)=>{
 const owner=beginCommerceEntitlementGeneration('account');
 const publish=(active:boolean,time:string)=>publishCommerceEntitlementChange({...owner,reason:'manual-refresh',snapshot:{serverTime:time,membership:{active,expiresAt:active?'2027-01-01T00:00:00Z':null}} as never});
 publish(false,'2026-10-25T01:00:00Z');
 const directory=await renderHook(()=>useQuestionBank(bank));
 const detail=await renderHook(()=>useQuestionBankTopic(bank,'category','topic'));
 await waitFor(()=>expect(directory.result.current.status).toBe('ready'));
 await waitFor(()=>expect(detail.result.current.status).toBe('ready'));
 await act(()=>{publish(true,'2026-10-25T01:00:01Z');});
 await waitFor(()=>expect(loadQuestionBank).toHaveBeenCalledTimes(2));
 await waitFor(()=>expect(questionBankRepository.getTopic).toHaveBeenCalledTimes(2));
 await act(()=>{publish(true,'2026-10-25T01:01:00Z');});
 expect(loadQuestionBank).toHaveBeenCalledTimes(2);
 expect(questionBankRepository.getTopic).toHaveBeenCalledTimes(2);
 await act(()=>{publish(false,'2026-10-25T02:00:00Z');});
 await waitFor(()=>expect(loadQuestionBank).toHaveBeenCalledTimes(3));
 await waitFor(()=>expect(questionBankRepository.getTopic).toHaveBeenCalledTimes(3));
});
it('does not restore a late free directory over the refreshed member directory',async()=>{
 const owner=beginCommerceEntitlementGeneration('account');
 let old!: (value:Awaited<ReturnType<typeof loadQuestionBank>>)=>void;
 jest.mocked(loadQuestionBank).mockImplementationOnce(()=>new Promise(resolve=>{old=resolve;}));
 const hook=await renderHook(()=>useQuestionBank('opi'));
 jest.mocked(loadQuestionBank).mockResolvedValue({dataset:{...dataset,access:{...dataset.access!,membershipActive:true}},source:'remote'});
 await act(()=>{publishCommerceEntitlementChange({...owner,reason:'purchase',snapshot:{serverTime:'2026-10-25T01:00:00Z',membership:{active:true}} as never});});
 await waitFor(()=>expect(hook.result.current.data?.access?.membershipActive).toBe(true));
 await act(()=>old({dataset,source:'remote'}));
 expect(hook.result.current.data?.access?.membershipActive).toBe(true);
});
